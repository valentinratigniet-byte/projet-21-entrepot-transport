-- CDC : plusieurs versions d'un voyage peuvent arriver (régularisations) -> la plus récente gagne
with src as ({{ dedup(source('tms', 'voyage'), 'voyage_id', 'cast(updated_at as timestamp) desc, _batch_id desc') }})
select
    cast(voyage_id as integer)                    as voyage_id,
    cmr,
    tete_lot_cmr,
    cast(nb_depotages as integer)                 as nb_depotages,
    cast(date_charge as date)                     as date_charge,
    cast(date_livre as date)                      as date_livre,
    client_cd,
    nullif(trim(relation_cd), '')                 as relation_cd,
    activite_cd,
    cast(tracteur as integer)                     as tracteur_num,
    remorque,
    {{ matricule('salarie_cd') }}                 as matricule,
    statut,
    cast(ca_facture as double)                    as ca_facture,
    cast(ca_reparti as double)                    as ca_reparti,
    cast(qt_livre as double)                      as qt_livre,
    cast(qt_facture as double)                    as qt_facture,
    cast(km_charge as double)                     as km_charge,
    cast(km_vide_av as double) + cast(km_vide_ap as double) as km_vide,
    cast(km_total as double)                      as km_total,
    cast(tps_charge_h as double)                  as tps_charge_h,
    cast(tps_livre_h as double)                   as tps_livre_h,
    cast(tps_cond_charge_h as double)             as tps_cond_charge_h,
    cast(tps_total_h as double)                   as tps_total_h,
    cast(mcv_couts_variables as double)           as mcv_couts_variables,
    cast(mcv_marge as double)                     as mcv_marge,
    cast(mcv_marge_lissee as double)              as mcv_marge_lissee,
    cast(mcv_peage_charge as double)              as mcv_peage_charge,
    cast(mcv_peage_vide as double)                as mcv_peage_vide,
    cast(mcv_ecot_charge as double)               as mcv_ecot_charge,
    cast(mcv_ecot_vide as double)                 as mcv_ecot_vide,
    cast(mcv_lavage_int as double)                as mcv_lavage_int,
    cast(nb_passages_peage as integer)            as nb_passages_peage,
    cast(attente_h as double)                     as attente_h,
    cast(attente_a_facturer_eur as double)        as attente_a_facturer_eur,
    livraison_samedi = '1'                        as est_livraison_samedi,
    double_depotage = '1'                         as est_double_depotage,
    ville_rupture,
    cast(updated_at as timestamp)                 as updated_at,
    cast(_batch_id as integer)                    as lot_import
from src
